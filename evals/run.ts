// Eval runner.
//   npm run evals                               rules only, prints a table
//   npm run evals -- --write                    also writes evals/RESULTS.md
//   npm run evals -- --recorded device=path.json --recorded cloud=path.json --write
//        adds columns for predictions recorded by the web app's eval page (#/evals),
//        which runs the real on-device (Gemini Nano) and cloud models in Chrome.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { piiMarkdown, runPiiEval, type PiiCase } from "./pii";
import { urlEvalMarkdown, type UrlCase } from "./urls";
import { groupBy, metrics, metricsRow, METRICS_HEADER, recordedScorer, rulesScorer, runScorer, type Case, type Row, type Scorer } from "./lib";

const here = dirname(fileURLToPath(import.meta.url));
const load = (f: string): Case[] => JSON.parse(readFileSync(join(here, "data", f), "utf8"));

export const SETS: Record<string, Case[]> = {
  "shield-paypal-ai: scam.json": load("scam.json"),
  "shield-paypal-ai: scam_holdout.json": load("scam_holdout.json"),
  "secondlook.json (new)": load("secondlook.json"),
};

async function main() {
  const args = process.argv.slice(2);
  const write = args.includes("--write");
  const scorers: Scorer[] = [rulesScorer];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--recorded") {
      const [name, path] = (args[++i] ?? "").split("=");
      if (!name || !path) throw new Error("--recorded expects name=path.json");
      scorers.push(recordedScorer(name, JSON.parse(readFileSync(path, "utf8"))));
    }
  }

  const all = Object.values(SETS).flat();
  const out: string[] = [];
  out.push("# Eval results", "");
  out.push(`Generated by \`npm run evals -- --write\` on ${new Date().toISOString().slice(0, 10)}. A message counts as flagged when the level is medium or high (score ≥ 30).`, "");
  out.push("> Caveat: the new cases were written alongside the new rules, so rules-only numbers on that set are optimistic. Only one rule bug was fixed after looking at results (genuine \"do not share your OTP\" warnings were read as OTP requests); the remaining misses are left in on purpose. They are the cases the AI tiers should catch.", "");
  out.push(`Datasets: ${Object.entries(SETS).map(([k, v]) => `${k} (${v.length})`).join(", ")}. Total ${all.length} labelled messages, ${all.filter((c) => c.scam).length} scams.`, "");

  for (const scorer of scorers) {
    const rowsBySet = new Map<string, Row[]>();
    for (const [name, cases] of Object.entries(SETS)) rowsBySet.set(name, await runScorer(scorer, cases));
    const allRows = [...rowsBySet.values()].flat();

    out.push(`## Scorer: ${scorer.name}`, "", METRICS_HEADER);
    for (const [name, rows] of rowsBySet) out.push(metricsRow(name, metrics(rows)));
    out.push(metricsRow("**All**", metrics(allRows)), "");

    const newRows = rowsBySet.get("secondlook.json (new)") ?? [];
    out.push("By category (new set):", "", METRICS_HEADER.replace("Set", "Category"));
    for (const [cat, rows] of groupBy(newRows, (r) => r.category ?? "other")) out.push(metricsRow(cat, metrics(rows)));
    out.push("", "By language (new set):", "", METRICS_HEADER.replace("Set", "Language"));
    for (const [lang, rows] of groupBy(newRows, (r) => r.lang ?? "en")) out.push(metricsRow(lang, metrics(rows)));

    const misses = allRows.filter((r) => r.scam !== r.flagged);
    out.push("", `Misses (${misses.length}):`, "");
    for (const r of misses) out.push(`- ${r.scam ? "**missed scam**" : "**false alarm**"} (score ${r.pred.score}): ${r.text.slice(0, 140).replace(/\|/g, "/")}${r.text.length > 140 ? "…" : ""}`);
    out.push("");
  }

  out.push(piiMarkdown(runPiiEval(JSON.parse(readFileSync(join(here, "data", "pii.json"), "utf8")) as PiiCase[])));

  out.push(urlEvalMarkdown(JSON.parse(readFileSync(join(here, "data", "urls.json"), "utf8")) as UrlCase[]));

  const md = out.join("\n");
  console.log(md);
  if (write) {
    writeFileSync(join(here, "RESULTS.md"), md);
    console.error(`\nwrote ${join(here, "RESULTS.md")}`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
